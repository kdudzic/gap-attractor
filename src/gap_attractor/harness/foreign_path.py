"""A negative-control memory built from another run's observed path.

``ForeignPathMemory`` intentionally shows the model assistant turns that were
produced in other, independent runs. It uses exactly the same message shape
and number of remembered turns as the built-in ``path_only`` memory, while
breaking the link between remembered choices and the current trajectory.

The history file is generated by ``scripts/build_foreign_path_control.py``.
The file and donor provenance are recorded in ``run.json`` under
``memory_settings`` so the condition remains auditable.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from gap_attractor.harness.memory import Memory


class ForeignPathMemory(Memory):
    """Show a deterministic sequence of real replies from other runs."""

    name = "foreign_path"

    def __init__(self, cfg):
        super().__init__(cfg)
        self.path = Path(str(cfg.experiment.foreign_history_file)).expanduser().resolve()
        self.document = json.loads(self.path.read_text(encoding="utf-8"))
        self.record_for_run = None
        self.recipient_start = None

    @classmethod
    def validate(cls, cfg) -> None:
        if str(cfg.experiment.get("action_format", "text")) != "text":
            raise ValueError("ForeignPathMemory currently requires experiment.action_format=text")
        source = cfg.experiment.get("foreign_history_file")
        if not source:
            raise ValueError("ForeignPathMemory requires experiment.foreign_history_file")
        path = Path(str(source)).expanduser().resolve()
        if not path.is_file():
            raise ValueError(f"foreign history file does not exist: {path}")
        try:
            document = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:
            raise ValueError(f"cannot read foreign history file {path}: {error}") from error
        if document.get("schema_version") != 1 or not isinstance(document.get("mapping"), dict):
            raise ValueError("foreign history file must have schema_version=1 and a mapping object")
        for start, record in document["mapping"].items():
            items = record.get("items") if isinstance(record, dict) else None
            if not isinstance(items, list) or any(not isinstance(item, dict) or "choice" not in item for item in items):
                raise ValueError(f"foreign history mapping for {start!r} has invalid items")

    def start(self, run) -> None:
        self.recipient_start = str(run.doc["start_page"])
        self.record_for_run = self.document["mapping"].get(self.recipient_start)
        if self.record_for_run is None:
            raise ValueError(f"no foreign history mapped for start page {self.recipient_start!r}")
        required = max(0, int(self.cfg.experiment.step_limit) - 1)
        available = len(self.record_for_run["items"])
        if available < required:
            raise ValueError(
                f"foreign history for {self.recipient_start!r} has {available} turns; {required} required"
            )

    def messages(self, rule: str, history: list[dict], observation: str) -> list[dict]:
        items = self.record_for_run["items"]
        if len(history) > len(items):
            raise ValueError("foreign history exhausted before the run ended")
        system = {"role": "system", "content": self.cfg.experiment.system_prompt + "\n\n" + rule}
        remembered = [
            {
                "role": "assistant",
                "content": json.dumps({"reasoning": item.get("reasoning"), "chose": item["choice"]}),
            }
            for item in items[:len(history)]
        ]
        return [system] + remembered + [{"role": "user", "content": observation}]

    def settings(self) -> dict:
        items = self.record_for_run["items"]
        donors = sorted({item["source_run_id"] for item in items})
        return {
            "control": "foreign_path",
            "history_file": str(self.path),
            "history_file_sha256": hashlib.sha256(self.path.read_bytes()).hexdigest(),
            "source_batch": self.document.get("source_batch"),
            "recipient_start_page": self.recipient_start,
            "turns_available": len(items),
            "donor_run_ids": donors,
            "matching": "same assistant-message format and turn count as path_only; donor token length is not matched",
        }
